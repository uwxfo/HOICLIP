"""Triplet-level HOI transition matrices for future-horizon anticipation.

Same file format as DetAnt1's datasets/priors/transition_matrix_vidhoi.py, but the
matrices live in HOI-triplet space instead of verb space: HOICLIP's head predicts
len(vidhoi_text_label) == 1127 HOI classes, so each matrix is [1127, 1127] with
T[i, j] = P(current triplet i | future triplet j).

TRANSITION_MATRICES_DETANT is loaded from transition_matrix_triplet_vidhoi.py
(generated by DetAnt1's calculate_triplet_transition_matrix_val.py). Its row/column
order was verified to match vidhoi_text_label's key order exactly: both are built
from VidHOI_annotation/triplet_categories_id.json's (verb, obj) order, so no
reindexing is needed.

ORIGINAL / DETANT_REVISED variants are not available yet; paste them in below,
keyed by horizon (1, 3, 5, 7), when generated. Until then, requesting those modes
falls back to an identity matrix, which makes the future-horizon prediction equal
to the current-frame prediction (a no-transition baseline) so the pipeline stays
runnable.
"""

import numpy as np

from datasets.vidhoi_text_label import vidhoi_text_label
from datasets.priors.transition_matrix_triplet_vidhoi import TRIPLET_TRANSITION_MATRICES_DETANT_VAL

NUM_HOI_CLASSES = len(vidhoi_text_label)

assert set(TRIPLET_TRANSITION_MATRICES_DETANT_VAL[1] and TRIPLET_TRANSITION_MATRICES_DETANT_VAL.keys()) == {1, 3, 5, 7}, \
    "transition_matrix_triplet_vidhoi.py must provide horizons 1, 3, 5, 7"
for _h, _m in TRIPLET_TRANSITION_MATRICES_DETANT_VAL.items():
    assert len(_m) == NUM_HOI_CLASSES and len(_m[0]) == NUM_HOI_CLASSES, (
        f"horizon {_h} matrix is {len(_m)}x{len(_m[0])}, expected "
        f"{NUM_HOI_CLASSES}x{NUM_HOI_CLASSES} (len(vidhoi_text_label))")

# Fill these in with the generated matrices, e.g. {1: [[...], ...], 3: ..., 5: ..., 7: ...}
TRANSITION_MATRICES_ORIGINAL = {}
TRANSITION_MATRICES_DETANT = TRIPLET_TRANSITION_MATRICES_DETANT_VAL
TRANSITION_MATRICES_DETANT_REVISED = {}

HORIZONS = (1, 3, 5, 7)


def _identity_matrices():
    identity = np.eye(NUM_HOI_CLASSES, dtype=np.float32)
    return {h: identity.copy() for h in HORIZONS}


def extract_transition_matrix(mode):
    """Return {horizon: matrix} for the requested mode.

    Mirrors the verb-space API so the eval code is identical across repos.
    """
    if "orig" in mode and TRANSITION_MATRICES_ORIGINAL:
        print("Loading TRANSITION_MATRICES_ORIGINAL (triplet).")
        return TRANSITION_MATRICES_ORIGINAL
    if "detant" in mode and "v2" in mode and TRANSITION_MATRICES_DETANT_REVISED:
        print("Loading TRANSITION_MATRICES_DETANT_REVISED (triplet).")
        return TRANSITION_MATRICES_DETANT_REVISED
    if "detant" in mode and TRANSITION_MATRICES_DETANT:
        print("Loading TRANSITION_MATRICES_DETANT (triplet).")
        return TRANSITION_MATRICES_DETANT

    print(f"No triplet transition matrix available for mode '{mode}'. "
          f"Falling back to identity ({NUM_HOI_CLASSES}x{NUM_HOI_CLASSES}).")
    return _identity_matrices()
